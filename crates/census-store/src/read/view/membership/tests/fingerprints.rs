use super::*;

fn check_vector(
    phase: &str,
    prefix: &str,
    rows: &[(&[u8], &[u8])],
    bytes: u64,
    digest: [u8; 32],
) -> TestResult {
    let dir = tempfile::tempdir()?;
    let store = Store::open(dir.path())?;
    for (key, raw) in rows.iter().rev() {
        store.journal.insert(*key, *raw)?;
    }
    let view = store.snapshot();
    let descriptor = JournalNamespace::new(phase, prefix)?;
    let count = u64::try_from(rows.len())?;
    let grant = ReadBudget {
        rows: count,
        bytes,
        record_bytes: MAX_JOURNAL_VALUE_BYTES,
    };
    let raw = view.journal_namespace_fingerprint(descriptor, grant)?;
    check!(eq; raw.digest, digest);
    check!(eq; raw.physical_rows(), count);
    check!(eq; raw.encoded_bytes(), bytes);
    let inventory = view.for_each_journal_root_bounded(descriptor, grant, |_| Ok(()))?;
    check!(eq; inventory.fingerprint().digest, digest);
    Ok(())
}

